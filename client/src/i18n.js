// Traducciones (español / inglés). El idioma sale de: elección guardada → idioma de Telegram → navegador.
const STORE_KEY = 'cr-lang';

function detect() {
  try { const saved = localStorage.getItem(STORE_KEY); if (saved === 'es' || saved === 'en') return saved; } catch { /* ignore */ }
  const code = window.Telegram?.WebApp?.initDataUnsafe?.user?.language_code || navigator.language || 'en';
  return code.toLowerCase().startsWith('es') ? 'es' : 'en';
}

export const LANG = detect();
export const LOCALE = LANG === 'es' ? 'es' : 'en-US';

export function setLang(lang) {
  try { localStorage.setItem(STORE_KEY, lang); } catch { /* ignore */ }
  location.reload(); // las texturas del mundo se generan al cargar: recargar aplica todo
}

