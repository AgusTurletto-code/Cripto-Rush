/** t('clave', { variables }) → texto en el idioma actual. */
export function t(key, vars = {}) {
  const v = T[LANG][key] ?? T.es[key] ?? key;
  if (typeof v !== 'string') return v;
  return v.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? `{${k}}`));
}
